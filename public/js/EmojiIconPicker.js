  init() {
    this.bindEvents();
    this.renderCategories();
    this.renderEmojis('表情');
  }

  bindEvents() {
    // 分类切换事件
    document.addEventListener('click', (e) => {
      if (e.target.classList.contains('emoji-category')) {
        const category = e.target.dataset.category;
        this.switchCategory(category);
      }
    });

    // 搜索事件
    const searchInput = document.getElementById('emojiSearch');
    if (searchInput) {
      searchInput.addEventListener('input', this.debounce((e) => {
        this.handleSearch(e.target.value.trim());
      }, 300));
    }

    // emoji选择事件
    document.addEventListener('click', (e) => {
      if (e.target.classList.contains('emoji-item')) {
        this.selectEmoji(e.target.textContent);
      }
    });

    // 自定义输入事件
    const customInput = document.getElementById('customEmojiInput');
    if (customInput) {
      customInput.addEventListener('input', (e) => {
        const value = e.target.value.trim();
        if (value) {
          this.selectEmoji(value);
        }
      });
    }

    // 绑定输入框事件
    this.bindInputEvents();

    // 绑定滚动按钮事件
    this.bindScrollButtons();
  }

  bindInputEvents(container = document) {
    const iconInputs = container.querySelectorAll('.icon-input');
    iconInputs.forEach(input => {
      // 移除已有的事件监听器，避免重复绑定
      input.removeEventListener('click', input._iconClickHandler);
      input.removeEventListener('focus', input._iconFocusHandler);
      
      // 创建事件处理函数，使用实例方法
      input._iconClickHandler = () => {
        this.showDropdown(input);
      };
      input._iconFocusHandler = () => {
        this.showDropdown(input);
      };
      
      // 绑定事件
      input.addEventListener('click', input._iconClickHandler);
      input.addEventListener('focus', input._iconFocusHandler);
      
      // 允许用户手动输入图标，不设置readonly属性
      input.style.cursor = 'text';
    });
  }

  debounce(func, wait) {
    let timeout;
    return function executedFunction(...args) {
      const later = () => {
        clearTimeout(timeout);
        func(...args);
      };
      clearTimeout(timeout);
      timeout = setTimeout(later, wait);
    };
  }

  bindScrollButtons() {
    const leftBtn = document.querySelector('.scroll-btn.left');
    const rightBtn = document.querySelector('.scroll-btn.right');
    const categoriesContainer = document.querySelector('.emoji-categories');
    
    if (leftBtn && rightBtn && categoriesContainer) {
      leftBtn.addEventListener('click', () => {
        categoriesContainer.scrollBy({ left: -100, behavior: 'smooth' });
      });
      
      rightBtn.addEventListener('click', () => {
        categoriesContainer.scrollBy({ left: 100, behavior: 'smooth' });
      });
    }
  }

  renderCategories() {
    const container = document.querySelector('.emoji-categories');
    if (!container) return;
    
    const categories = Object.keys(this.emojiData);
    const html = categories.map(category => {
      return `<button class="emoji-category" data-category="${category}">${category}</button>`;
    }).join('');
    
    container.innerHTML = html;
    
    // 默认选中第一个分类
    const firstCategory = container.querySelector('.emoji-category');
    if (firstCategory) {
      firstCategory.classList.add('active');
    }
  }

  renderEmojis(category) {
    const container = document.getElementById('emojiGrid');
    if (!container || !this.emojiData[category]) return;
    
    const emojis = this.emojiData[category];
    const html = emojis.map(emoji => {
      return `<div class="emoji-item" title="${emoji}">${emoji}</div>`;
    }).join('');
    
    container.innerHTML = html;
  }

  switchCategory(category) {
    // 更新分类按钮状态
    document.querySelectorAll('.emoji-category').forEach(btn => {
      btn.classList.remove('active');
    });
    
    const activeBtn = document.querySelector(`[data-category="${category}"]`);
    if (activeBtn) {
      activeBtn.classList.add('active');
    }
    
    // 渲染对应分类的emoji
    this.renderEmojis(category);
    
    // 清空搜索框
    const searchInput = document.getElementById('emojiSearch');
    if (searchInput) {
      searchInput.value = '';
    }
  }

